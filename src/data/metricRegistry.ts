// ── HELPERS ──────────────────────────────────────────

export function getMetricsByObjective(objective: CampaignObjective): MetricDefinition[] {
  return SYSTEM_METRICS.filter((m) => m.objectives.includes(objective))
}

export function getMetricByKey(key: string): MetricDefinition | undefined {
  return SYSTEM_METRICS.find((m) => m.key === key)
}

export function getMetricsByCategory(category: string): MetricDefinition[] {
  return SYSTEM_METRICS.filter((m) => m.category === category)
}
